ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS min_display_count      integer NOT NULL DEFAULT 5,
  ADD COLUMN IF NOT EXISTS module_mental_health   boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS module_company_support boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS module_work_life       boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS module_exercise        boolean NOT NULL DEFAULT false;

-- =====================================================
-- Step 2: survey_rounds テーブルの新規作成
-- =====================================================
CREATE TABLE IF NOT EXISTS survey_rounds (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_code text        NOT NULL REFERENCES clients(code),
  title       text        NOT NULL,
  started_at  timestamptz,
  ended_at    timestamptz,
  created_at  timestamptz DEFAULT now()
);

ALTER TABLE survey_rounds ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "survey_rounds_admin"        ON survey_rounds;
DROP POLICY IF EXISTS "survey_rounds_client_admin" ON survey_rounds;
DROP POLICY IF EXISTS "survey_rounds_anon"         ON survey_rounds;

CREATE POLICY "survey_rounds_admin" ON survey_rounds FOR ALL
  USING ((auth.jwt() -> 'app_metadata' ->> 'role') = 'system_admin');

CREATE POLICY "survey_rounds_client_admin" ON survey_rounds FOR SELECT
  USING (
    (auth.jwt() -> 'app_metadata' ->> 'role') = 'client_admin'
    AND client_code = (auth.jwt() -> 'app_metadata' ->> 'client_code')
  );

-- anon はアンケートURL上の実施回を参照するために SELECT のみ許可
CREATE POLICY "survey_rounds_anon" ON survey_rounds FOR SELECT
  USING (auth.role() = 'anon');

