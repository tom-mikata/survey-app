-- 心の健康モジュール（問17、6項目）
CREATE TABLE IF NOT EXISTS mental_health_responses (
  id                 bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  survey_response_id text        NOT NULL REFERENCES survey_responses(id),
  q17_score          integer     NOT NULL CHECK (q17_score BETWEEN 0 AND 4),
  q18_score          integer     NOT NULL CHECK (q18_score BETWEEN 0 AND 4),
  q19_score          integer     NOT NULL CHECK (q19_score BETWEEN 0 AND 4),
  q20_score          integer     NOT NULL CHECK (q20_score BETWEEN 0 AND 4),
  q21_score          integer     NOT NULL CHECK (q21_score BETWEEN 0 AND 4),
  q22_score          integer     NOT NULL CHECK (q22_score BETWEEN 0 AND 4),
  created_at         timestamptz DEFAULT now()
);

-- 会社のサポートモジュール（問18、4項目）
CREATE TABLE IF NOT EXISTS company_support_responses (
  id                 bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  survey_response_id text        NOT NULL REFERENCES survey_responses(id),
  q23_score          integer     NOT NULL CHECK (q23_score BETWEEN 1 AND 7),
  q24_score          integer     NOT NULL CHECK (q24_score BETWEEN 1 AND 7),
  q25_score          integer     NOT NULL CHECK (q25_score BETWEEN 1 AND 7),
  q26_score          integer     NOT NULL CHECK (q26_score BETWEEN 1 AND 7),
  created_at         timestamptz DEFAULT now()
);

-- 仕事以外の負担モジュール（問19〜20）
CREATE TABLE IF NOT EXISTS work_life_responses (
  id                 bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  survey_response_id text        NOT NULL REFERENCES survey_responses(id),
  role_impact        text        NOT NULL,
  support_desire     text,
  created_at         timestamptz DEFAULT now()
);

-- 運動習慣モジュール（問21〜22）
CREATE TABLE IF NOT EXISTS exercise_responses (
  id                 bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  survey_response_id text        NOT NULL REFERENCES survey_responses(id),
  has_exercise_habit boolean     NOT NULL,
  exercise_days      integer     CHECK (exercise_days BETWEEN 1 AND 7),
  created_at         timestamptz DEFAULT now()
);

